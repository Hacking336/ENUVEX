package com.jobskills.controller;

import com.jobskills.model.UploadedFile;
import com.jobskills.repository.UploadedFileRepository;
import lombok.RequiredArgsConstructor;
import org.springframework.http.CacheControl;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.Optional;
import java.util.concurrent.TimeUnit;

/**
 * Serves user-uploaded images.
 *
 * <p>Files come from the database rather than the container filesystem, which
 * managed hosts such as Render wipe on every restart, redeploy and spin-down.
 * URLs are unchanged ({@code /uploads/{filename}}) so stored profile rows keep
 * working.
 */
@RestController
@RequestMapping("/uploads")
@RequiredArgsConstructor
public class FilesController {

    private final UploadedFileRepository uploadedFileRepository;

    @GetMapping("/{filename:.+}")
    public ResponseEntity<byte[]> downloadFile(@PathVariable String filename) {
        // Filenames are generated by the app, so anything path-like is a probe.
        if (filename.contains("..") || filename.contains("/") || filename.contains("\\")) {
            return ResponseEntity.notFound().build();
        }

        Optional<UploadedFile> stored = uploadedFileRepository.findById(filename);
        if (stored.isEmpty()) {
            return ResponseEntity.notFound().build();
        }

        UploadedFile file = stored.get();
        return ResponseEntity.ok()
            // Filenames carry a random UUID prefix, so the bytes never change.
            .cacheControl(CacheControl.maxAge(365, TimeUnit.DAYS).cachePublic().immutable())
            .contentType(contentTypeOf(file.getContentType()))
            .body(file.getData());
    }

    private MediaType contentTypeOf(String stored) {
        if (stored != null) {
            try {
                return MediaType.parseMediaType(stored);
            } catch (RuntimeException e) {
                // Fall through to the generic type below.
            }
        }
        return MediaType.APPLICATION_OCTET_STREAM;
    }
}
